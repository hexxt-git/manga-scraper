const failedChapters: string[] = [];

// one chapter at a time; each chapter already downloads its images in parallel
for (const url of urls) {
  console.log(`\n== ${url}`);
  const num = [...url.matchAll(/-([\d.]+)/g)].at(-1)?.[1];
  const chapterFolder = num ? `ch_${num.replaceAll(".", "-")}` : "images";
  const outDir = join("out", FOLDER, chapterFolder);

  try {
    await scrapeImages(url, {
      selector: SELECTOR,
      referer: REFERER,
      outDir,
    });
  } catch (err) {
    console.error(`✗ ${url}: ${(err as Error).message}`);
    failedChapters.push(url);
  }

  if (STOP_AT && num === STOP_AT.replace(/^chapter-/, "")) {
    console.log(
      `\nReached target chapter (${STOP_AT}). Stopping as requested.`,
    );
    break;
  }
}

if (failedChapters.length > 0) {
  console.error(
    `\nCompleted with ${failedChapters.length} failed chapter(s):\n${failedChapters.join("\n")}`,
  );
  process.exit(1);
} else {
  console.log("\nDone! All processed chapters completed successfully.");
}
